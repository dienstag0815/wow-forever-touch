local function choose()
    local app = ns.appLanguage
    if app == "de" or app == "en" then return app, "app" end
    if GetLocale and GetLocale() == "deDE" then return "de", "client" end
    return "en", "client"
end

local lang, source = choose()
ns.lang, ns.langSource = lang, source
ns.texts = S

local active, fallback = S[lang], S.en
ns.L = setmetatable({}, {
    __index = function(_, key)
        local value = active[key]
        if value == nil then value = fallback[key] end
        if value == nil then value = tostring(key) end
        return value
    end,
})
